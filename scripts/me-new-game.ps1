package dev.myengine.games.__PACKAGE__

import dev.myengine.core.SeededRandom
import dev.myengine.core.stableHashOf

data class CanonicalScenarioResult(
    val trajectory: List<String>,
    val finalHash: String,
)

object CanonicalScenario {
    private const val TICKS = 12
    private const val DEFAULT_SEED = 7L

    fun run(seed: Long = DEFAULT_SEED): CanonicalScenarioResult {
        val random = SeededRandom(seed)
        val trajectory = buildList {
            repeat(TICKS) { tick ->
                val signal = random.nextInt(100)
                add(stableHashOf {
                    add("canonical")
                    add(tick)
                    add(signal)
                })
            }
        }
        val finalHash = stableHashOf {
            add("canonical")
            add(seed)
            trajectory.forEach(::add)
        }
        return CanonicalScenarioResult(trajectory, finalHash)
    }
}
