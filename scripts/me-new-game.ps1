    if ($Slug -cnotmatch '^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$') {
        throw "Slug must be lower-kebab-case, start with a letter, and contain only letters, digits, and single hyphens."
    }

    $repoRoot = [System.IO.Path]::GetFullPath($Root)
    $gamesRoot = Assert-ContainedPath -Path (Join-Path $repoRoot "games") -Container $repoRoot
    $settingsPath = Join-Path $repoRoot "settings.gradle.kts"
    if (-not (Test-Path -LiteralPath $settingsPath -PathType Leaf)) {
        throw "settings.gradle.kts was not found under '$repoRoot'."
    }

    $gamePath = Assert-ContainedPath -Path (Join-Path $gamesRoot $Slug) -Container $gamesRoot
    $stagePath = Assert-ContainedPath -Path (Join-Path $gamesRoot ("." + $Slug + ".scaffold")) -Container $gamesRoot
    if (Test-Path -LiteralPath $gamePath) {
        throw "Refusing to overwrite existing game '$Slug' at '$gamePath'."
    }
    if (Test-Path -LiteralPath $stagePath) {
        throw "Refusing to reuse existing staging directory '$stagePath'; archive it manually before retrying."
    }

    $settingsText = [System.IO.File]::ReadAllText($settingsPath)
    $modulePath = ":games:$Slug"
    $includeLine = 'include("' + $modulePath + '")'
    $projectLine = 'project("' + $modulePath + '").projectDir = file("games/' + $Slug + '")'
    if ($settingsText.Contains($includeLine) -or $settingsText.Contains($projectLine)) {
        throw "settings.gradle.kts already contains wiring for '$modulePath'."
    }

    $packageName = $Slug.Replace('-', '_')
    $packPath = "content/$Slug"
    $files = [ordered]@{}

    Add-Template $files "build.gradle.kts" @'
