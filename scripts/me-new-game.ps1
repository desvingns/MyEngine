)

$ErrorActionPreference = "Stop"
if ([string]::IsNullOrWhiteSpace($Root)) {
    $Root = Split-Path -Parent $PSScriptRoot
}

function Write-Utf8NoBom {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [Parameter(Mandatory = $true)][string]$Content
    )

    $parent = Split-Path -Parent $Path
    if ($parent) {
        New-Item -ItemType Directory -Force -Path $parent | Out-Null
    }
    $encoding = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($Path, $Content, $encoding)
}

function Assert-ContainedPath {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [Parameter(Mandatory = $true)][string]$Container
    )

    $fullPath = [System.IO.Path]::GetFullPath($Path)
    $fullContainer = ([System.IO.Path]::GetFullPath($Container)).TrimEnd([System.IO.Path]::DirectorySeparatorChar) + [System.IO.Path]::DirectorySeparatorChar
    if (-not $fullPath.StartsWith($fullContainer, [System.StringComparison]::OrdinalIgnoreCase)) {
        throw "Resolved path '$fullPath' escapes '$fullContainer'."
    }
    return $fullPath
}

function Add-Template {
    param(
        [Parameter(Mandatory = $true)][System.Collections.IDictionary]$Files,
        [Parameter(Mandatory = $true)][string]$RelativePath,
        [Parameter(Mandatory = $true)][string]$Content
    )
    $Files[$RelativePath] = $Content.TrimStart("`r", "`n") + "`n"
}

